// Build-time typst compilation: a Vite plugin that runs in Node (never inside
// the Cloudflare worker graph, which cannot bundle the native .node addon) and
// writes the compiled posts to a generated module the pages import as data.
//
// Why a generated module: the worker environment forces `resolve.noExternal:
// true` (Cloudflare Vite plugin), so importing typst-ts-node-compiler from
// server code fails with UNLOADABLE_DEPENDENCY on the .node binary. The
// plugin below compiles every posts/*.typ at build start and emits
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import type { Plugin } from 'vite'
import { NodeCompiler } from '@myriaddreamin/typst-ts-node-compiler'
import { extractHeadings, extractMeta, injectHeadingIds } from '../lib/typst-pure'

export interface CompiledTypstPost {
  slug: string
  url: string
  title: string
  date: string
  description: string
  content: string
  toc: { level: number; text: string; rawText: string; id: string }[]
}

const generatedDir = '.void'
const generatedFile = join(generatedDir, 'typst-posts.ts')

const compilePosts = async (): Promise<CompiledTypstPost[]> => {
  const postsDir = resolve(process.cwd(), 'posts')
  const slugs = readdirSync(postsDir)
    .filter((name) => name.endsWith('.typ') && name !== 'lib.typ')
    .sort()

  const workspace = join(postsDir, '..')
  const compiler = await NodeCompiler.create({ workspace })
  compiler.addSource(
    join(postsDir, 'lib.typ'),
    readFileSync(join(postsDir, 'lib.typ'), 'utf8'),
  )

  const posts: CompiledTypstPost[] = []
  for (const name of slugs) {
    const slug = name.replace(/\.typ$/, '')
    const source = readFileSync(join(postsDir, name), 'utf8')
    const file = join(postsDir, name)
    compiler.addSource(file, source)
    const result = compiler.compileHtml({ mainFilePath: file })
    if (result.hasError()) {
      result.printErrors()
      throw new Error(`typst compilation failed for ${slug}`)
    }
    const document = result.result
    if (document === null) throw new Error(`typst compilation produced no document for ${slug}`)
    const full = compiler.html(document)
    if (full === null) throw new Error(`typst compilation produced no HTML for ${slug}`)
    const body = full.slice(full.indexOf('<body>') + 6, full.lastIndexOf('</body>'))
    const toc = extractHeadings(source).map((entry) => ({ ...entry, rawText: entry.text }))
    posts.push({
      slug,
      url: `/blog/${slug}`,
      ...extractMeta(source),
      content: injectHeadingIds(body, toc),
      toc,
    })
  }
  posts.sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : a.slug.localeCompare(b.slug)))
  return posts
}

export const typstPrecompile = (): Plugin => ({
  name: 'typst-precompile',
  async buildStart() {
    const posts = await compilePosts()
    mkdirSync(generatedDir, { recursive: true })
    const body = `// AUTO-GENERATED by src/build/typst-precompile.ts — do not edit.\nexport const posts = ${JSON.stringify(posts)} as const\n`
    writeFileSync(generatedFile, body, 'utf8')
    this.info(`typst: compiled ${posts.length} post(s)`)
  },
})
